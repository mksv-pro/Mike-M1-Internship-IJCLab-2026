def write_all(only=None):
    names = list(ALL) if not only else [n for n in only if n in ALL]
    t0 = time.perf_counter()
    for name in names:
        print(f"[{name}]", flush=True)
        ALL[name]()
    print("done in %.0f s" % (time.perf_counter() - t0))


if __name__ == "__main__":
    write_all(sys.argv[1:] or None)
