# --- formatting -------------------------------------------------------

def _sci(x, digits=1):
    """1.6e-04 as $1.6\\times10^{-4}$, and a missing value as a dash."""
    x = float(x)
    if not np.isfinite(x):
        return "--"
    if x == 0.0:
        return "$0$"
    exp = int(np.floor(np.log10(abs(x))))
    mant = x / 10.0 ** exp
    return rf"${mant:.{digits}f}\times10^{{{exp}}}$"


def _num(x, digits=2):
    return "--" if not np.isfinite(float(x)) else f"${float(x):.{digits}f}$"


def _gain(x):
    """A gain: no decimal past ten, one below it, a dash if missing. Formatted
    here so the rule cannot drift between two tables."""
    x = float(x)
    if not np.isfinite(x):
        return "--"
    return rf"$\times{x:.0f}$" if x >= 10 else rf"$\times{x:.1f}$"


def _header(block, extra=""):
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    where = cache.name() or "results"
    return ("% GENERATED by pipeline.tables -- do not edit.\n"
            f"% cache={where}  block={block}  written={stamp}\n"
            f"% Regenerate with:  api.tables()\n"
            + (f"% {extra}\n" if extra else ""))


def _short(caption, limit=92, floor=30):
    """The list-of-tables entry: the caption's first sentence, cut back at a
    clause boundary if it is longer than a line."""
    head = re.split(r"(?<=[a-z0-9)])\.\s", caption.strip(), maxsplit=1)[0]
    head = re.sub(r"\s+", " ", head).rstrip(".")
    plain = re.sub(r"\\[a-zA-Z]+\{[^{}]*\}", "xxx", head)
    plain = re.sub(r"[\\{}$]", "", plain)
    if len(plain) <= limit:
        return head
    best = None
    for m in re.finditer(r"(?<=[a-z0-9)]),\s|:\s|;\s", head):
        cut = head[:m.start()].rstrip(" ,;:")
        n = len(re.sub(r"[\\{}$]", "", re.sub(r"\\[a-zA-Z]+\{[^{}]*\}", "xxx", cut)))
        if floor <= n <= limit and (best is None or n > best[1]):
            best = (cut, n)
    return best[0] if best else head


def _tabular(header_rows, body_rows, spec, caption, label, block, note="",
             compact=False):
    """One table environment. `compact` (tabcolsep 2pt) is for a table too wide
    for the text block; the body size is set by main.tex, so it is not touched
    here.
    """
    lines = [_header(block, note),
             r"\begin{table}[H]", r"\centering",
             rf"\caption[{_short(caption)}]{{{caption}}}", rf"\label{{{label}}}"]
    if compact:
        lines += [r"\setlength{\tabcolsep}{2pt}"]
    lines += [rf"\begin{{tabular}}{{@{{}}{spec}@{{}}}}", r"\toprule"]
    lines += header_rows
    lines.append(r"\midrule")
    lines += body_rows
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


