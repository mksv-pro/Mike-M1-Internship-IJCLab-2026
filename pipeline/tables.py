def table_manifold(systems=SUITE):
    """Rank, its share of the ambient dimension, and what each method achieves.

    Columns 5-7 are `observable_vs_emulators` medians over every validation draw
    and energy node; column 4 is the error at the top rung of the rank ladder.
    """
    rows, eps = [], None
    n_demo, n_draw, n_node = None, None, None
    for key in systems:
        system = SYSTEMS[key]
        d, meta = cache.read(key, "manifold")
        # from the block's metadata, not a live probe: the quoted rank must be
        # the one the numbers beside it were computed at.
        nb = int(meta.get("nb") or calibration_for(key).nb)
        eps = meta.get("eps_sol", eps)
        dim = system.n_channels * system.N
        err_sigma = np.asarray(d["err_sigma"], dtype=float)
        top = float(np.nanmedian(err_sigma[-1])) if err_sigma.size else np.nan
        notes = views.observable_vs_emulators(key)["error"].notes
        # columns 5 and 6-7 are the same method at the same rank, differing only
        # in what they average over (the caption says which).
        n_demo = err_sigma.shape[1] if err_sigma.ndim == 2 else n_demo
        d_exc, _ = cache.read(key, "excitation")
        err_exc = np.asarray(d_exc["err_rbm"])
        if err_exc.ndim == 2:
            n_draw, n_node = err_exc.shape
        rows.append(rf"{system.label} & ${dim}$ & ${nb}$ & "
                    rf"${100.0 * nb / dim:.0f}\%$ & {_sci(top)} & "
                    rf"{_sci(notes.get('median_rbm', np.nan))} & "
                    rf"{_sci(notes.get('median_lrom', np.nan))} \\")

    caption = (
        rf"The manifold, and what the emulators achieve on it. The rank is the "
        rf"one the truncation criterion selects at "
        # the document's symbol (\epsilon_{\rm tol}), not the code's variable
        # name (eps_sol).
        rf"$\epsilon_{{\rm tol}}={_sci(eps, 0)[1:-1]}$, and the three error "
        rf"columns are all quoted at it. Column~5 is obtained at the "
        rf"demonstration energy alone, over ${n_demo}$ validation parameters; "
        rf"columns~6 and~7 over ${n_draw}$ validation parameters and all "
        rf"${n_node}$ energies of the window.")
    return _tabular(
        [r"& & \multicolumn{2}{c}{retained rank} "
         r"& \multicolumn{3}{c}{median relative error on $\sigma$, at that rank}\\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}",
         r"& & & & at $E_{\rm demo}$ "
         r"& \multicolumn{2}{c}{over the energy window}\\",
         r"\cmidrule(lr){5-5}\cmidrule(lr){6-7}",
         r"System & $N_cN$ & retained rank $n_b$ & $n_b/N_cN$ & RBM & RBM & LROM \\"],
        rows, "lrrrrrr", caption, "tab:manifold", "manifold + excitation")


def operating_rows(system_key):
    """The operating configuration of each method, with its cost and its error.

    Shared with `table_cost` and `macros()` so a sentence never names a
    configuration the table beside it does not. The operating point is
    `metrics.operating_point` (cheapest configuration clearing the tolerance),
    never chosen by eye.

    Returns (solver_costs, [per-method dict]). The error is measured on the
    quantity the cost-accuracy sheets use -- off-diagonal where one exists,
    diagonal otherwise.
    """
    d, meta = cache.read(system_key, "cat")
    # from the block, not a live probe: the training size the block used.
    n_train = int(meta.get("n_train") or calibration_for(system_key).Ns)

    method = np.asarray(d["method"]).astype(str)
    nb = np.asarray(d["nb_kept"], dtype=float)
    kd = np.asarray(d["K_diag"], dtype=float)
    kc = np.asarray(d["K_coup"], dtype=float)
    t_on = np.asarray(d["t_online"], dtype=float) * 1e3
    quantity = ("err_Sab" if np.isfinite(np.asarray(d["err_Sab"])).any()
                else "err_S00")
    err = np.asarray(d[quantity], dtype=float)

    solver = dict(
        n_train=n_train, quantity=quantity,
        # the p95 columns are read off this many draws (a tail statistic without
        # its sample size is not a measurement).
        n_valid=int(meta.get("n_valid") or 0),
        t_rmat=float(np.median(np.asarray(d["t_rmat"], dtype=float))) * 1e3,
        t_full=float(np.median(np.asarray(d["t_dbmm_full"], dtype=float))) * 1e3,
        t_V=float(np.median(np.asarray(d["t_dbmm_V"], dtype=float))) * 1e3)

    out = []
    for m, tag in (("rbm", "RBM"), ("lrom", "LROM")):
        combos, seen = [], set()
        for i in range(method.size):
            sig = (method[i], nb[i], kd[i], kc[i])
            if method[i] == m and sig not in seen:
                seen.add(sig)
                combos.append(sig)
        if not combos:
            continue
        costs, errs, labels = [], [], []
        for (_, b, a, c) in combos:
            sel = (method == m) & (nb == b) & (kd == a) & (kc == c)
            costs.append(float(np.median(t_on[sel])))
            errs.append(float(np.nanmedian(err[sel])))
            labels.append(rf"$n_b\,{b:.0f}$" if m == "rbm"
                          else (rf"$K\,{a:.0f}{{+}}{c:.0f}$" if c
                                else rf"$K\,{a:.0f}$"))
        i = metrics.operating_point(errs, costs)
        if i is None:                    # nothing clears the tolerance
            i = int(np.argmin(errs))
        sel = ((method == m) & (nb == combos[i][1])
               & (kd == combos[i][2]) & (kc == combos[i][3]))
        sample = err[sel][np.isfinite(err[sel])]
        p5, p95 = (np.percentile(sample, [5, 95]) if sample.size
                   else (np.nan, np.nan))

        # gain against the affine-split solver from the PAIRED measurement
        # (baseline and prediction on the same theta, microseconds apart, so the
        # clock drift divides out). The other two gains have no paired partner
        # and stay ratios of medians, quoted to the nearest integer.
        if "t_dbmm_paired" in d:
            paired = np.asarray(d["t_dbmm_paired"], dtype=float)[sel] * 1e3
            on = t_on[sel]
            good = np.isfinite(paired) & np.isfinite(on) & (on > 0)
            gain_V = (float(np.median(paired[good] / on[good])) if good.any()
                      else solver["t_V"] / costs[i])
        else:
            gain_V = solver["t_V"] / costs[i]

        out.append(dict(method=m, tag=tag, label=labels[i], cost=costs[i],
                        err=errs[i], p5=float(p5), p95=float(p95),
                        gain_rmat=solver["t_rmat"] / costs[i],
                        gain_full=solver["t_full"] / costs[i],
                        gain_V=gain_V))
    return solver, out


def table_cost(systems=SUITE):
    """One forward evaluation, three baselines, and what the emulator costs.

    Every number here comes from `operating_rows`, which is also what the
    inline macros are built from.
    """
    rows, n_valid_seen = [], 0
    for key in systems:
        system = SYSTEMS[key]
        solver, configs = operating_rows(key)
        n_valid_seen = max(n_valid_seen, solver.get("n_valid", 0))
        first = True
        for c in configs:
            head = (rf"{system.label} & {c['tag']} & ${solver['n_train']}$ & "
                    rf"{_num(solver['t_rmat'], 1)} "
                    rf"& {_num(solver['t_full'], 1)} & {_num(solver['t_V'], 2)}"
                    if first else rf" & {c['tag']} & & & &")
            rows.append(
                rf"{head} & {c['label']} & {_num(c['cost'], 2)} & "
                rf"{_gain(c['gain_rmat'])} & "
                rf"{_gain(c['gain_full'])} & "
                rf"{_gain(c['gain_V'])} & "
                rf"{_sci(c['err'])} & {_sci(c['p5'])}--{_sci(c['p95'])} \\")
            first = False
        rows.append(r"\addlinespace[2pt]")
    if rows and rows[-1].startswith(r"\addlinespace"):
        rows.pop()

    caption = (
        r"The cost of one forward evaluation, and what it amortises to. "
        r"Medians over the timed draws, each the minimum of at least seven "
        r"repetitions, on one core. The two error columns are the metric of "
        r"Table~\ref{tab:metrics} on the elements of $\mathbf{U}$: the worst "
        r"off-diagonal element that exists where the system is coupled, the "
        r"elastic element where it is not. They are read off "
        rf"${n_valid_seen}$ validation draws, none of them seen in training; the "
        r"p95 in particular needs a sample of that size to be an estimate rather "
        r"than close to the largest value observed. Absolute times reproduce to between $5$ and "
        r"$30$ per cent between runs, so the gain against the $V$-only baseline "
        r"is \emph{paired}, baseline and prediction timed on the same $\theta$ "
        r"microseconds apart; the other two are unpaired and rounded. It is a median of per-draw ratios, so it does not equal the ratio of the two median columns. "
        r"\textbf{The R-matrix column is an upper bound, not the cost of the "
        r"method}: that implementation rebuilds a $\theta$-independent kinetic "
        r"matrix on every call and inverts where $N_c$ right-hand sides would "
        r"do. The gain against $V$ only is the "
        r"one to defend. Each configuration is the cheapest the autocalibration "
        r"proposes that clears the posterior tolerance. "
        r"Two things this table is not. The offline cost is paid \emph{per "
        r"energy node and per $J^\pi$ block}: a campaign over twenty energies "
        r"pays it twenty times, so the training minutes quoted here are not the "
        r"training cost of a full campaign. And every time in it is Python "
        r"against Python. It is the ratio that carries over to another "
        r"implementation, not the absolute values: a compiled solver would move "
        r"both the baseline and the emulator columns.")
    return _tabular(
        [r"& & & \multicolumn{3}{c}{solver, ms per evaluation}"
         r"  & \multicolumn{2}{c}{emulator}"
         r"  & \multicolumn{3}{c}{gain against}"
         r"  & \multicolumn{2}{c}{error} \\",
         r"\cmidrule(lr){4-6}\cmidrule(lr){7-8}\cmidrule(lr){9-11}"
         r"\cmidrule(lr){12-13}",
         r"System & method & $n_{\rm train}$ & R-matrix & rebuild & split"
         r"  & operating config. & ms & R-matrix & rebuild & split"
         r"  & median & p5--p95 \\"],
        rows, "llrrrrrrrrrrr", caption, "tab:cost", "cat",
        note="R-matrix column is an upper bound, not the method's cost",
        compact=True)


