_TEX_DIGITS = str.maketrans("0123456789", "ZOTHFVSEIN")

#: Systems the amplitude argument names, in sentence order. Not SUITE: n+58Ni is
#: the one system whose coupling parameter is absent from the diagonal.
AMPLITUDE_SYSTEMS = ("alpha12C_band", "n58Ni", "n238U", "alpha24Mg")


def _amplitude_ratio(key, n_r=200):
    """How much further the diagonal block travels over the box than the coupling.

    Each parameter is pushed to the top of its box in turn; the largest absolute
    change of any diagonal potential over the mesh is taken, and the same for
    the coupling block. Absolute, not relative: what decides where a maxvol pass
    puts its points is the size of the signature entries, not their size
    relative to their own block. Reads the preset, not the cache.
    """
    system = SYSTEMS[key]
    channels, model, theta_c, bounds = system.preset_fn()
    r = np.linspace(1e-3, system.R, n_r)
    V_diag_c, V_coup_c = model(theta_c)
    base_diag = [np.asarray(V_diag_c(r, c), dtype=complex) for c in channels]
    base_coup = np.asarray(V_coup_c(r, channels[0], channels[1]), dtype=complex)

    d_max = c_max = 0.0
    for j in range(len(theta_c)):
        theta = theta_c.copy()
        theta[j] = bounds[j, 1]
        Vd, Vc = model(theta)
        d_max = max(d_max, max(
            np.max(np.abs(np.asarray(Vd(r, c), dtype=complex) - b))
            for c, b in zip(channels, base_diag)))
        c_max = max(c_max, np.max(np.abs(
            np.asarray(Vc(r, channels[0], channels[1]), dtype=complex)
            - base_coup)))
    return float(d_max / max(c_max, 1e-30))


def _macro_name(tag, system_key):
    r"""A TeX control sequence name: letters only, digits spelled out
    (\NstarRbmNFZCa, not \NstarRbmN40Ca -- TeX allows no digits in control
    sequences)."""
    raw = tag + "".join(w.capitalize() for w in
                        system_key.replace("+", "_").split("_"))
    return "".join(c for c in raw if c.isalnum()).translate(_TEX_DIGITS)


#: Bands the summary table reads its verdict symbols off. Presentation only:
#: "clears" is the same EPS_POST metrics.operating_point applies; the middle
#: band keeps a configuration on the threshold from printing as a plain failure.
VERDICT_MARGIN = 1.5      # within this factor of the tolerance: on the threshold
GAIN_REAL = 1.5           # at or above: a gain worth having
GAIN_NONE = 1.05          # below: the reduction returns nothing


def _verdict_error(x, tol=None):
    """Y, A or N for an error against the posterior tolerance."""
    from .style import EPS_POST
    tol = EPS_POST if tol is None else tol
    if not np.isfinite(x):
        return "N"
    if x <= tol:
        return "Y"
    return "A" if x <= VERDICT_MARGIN * tol else "N"


def _verdict_gain(g):
    """Y, A or N for an online gain against the affine-split solver."""
    if not np.isfinite(g):
        return "N"
    if g >= GAIN_REAL:
        return "Y"
    return "A" if g >= GAIN_NONE else "N"


def _log(x):
    r"""log10(x), for a TikZ coordinate on a logarithmic axis (a $6.8\times
    10^{-3}$ macro is unusable as a coordinate). Non-finite emits a dash, so a
    figure built on one fails to compile rather than drawing a stray point.
    """
    return f"{np.log10(x):.2f}" if np.isfinite(x) and x > 0 else "--"


def _sigfig(x, n=2):
    """x rounded to n significant figures, rendered without a decimal point."""
    if not np.isfinite(x) or x == 0:
        return "0"
    mag = int(np.floor(np.log10(abs(x))))
    step = 10.0 ** (mag - n + 1)
    return f"{round(round(x / step) * step):d}"


def macros(systems=SUITE):
    r"""The numbers the prose quotes, as \newcommand definitions, so a paragraph
    regenerates with the figure it describes."""
    lines = [_header("cat + amortisation + manifold")]
    # the amplitude ratios behind the by-block budget split: four numbers in one
    # sentence, the shape that rots when typed.
    for key in AMPLITUDE_SYSTEMS:
        lines.append(rf"\newcommand{{\{_macro_name('AmpRatio', key)}}}"
                     rf"{{{_sigfig(_amplitude_ratio(key), 2)}}}")
    for key in systems:
        amort = views.amortisation(key)["breakeven"].notes
        _, cat_meta = cache.read(key, "cat")
        _, man_meta = cache.read(key, "manifold")
        for note, tag in (("cross_rbm", "NstarRbm"), ("cross_lrom", "NstarLrom")):
            v = amort.get(note, np.nan)
            lines.append(
                rf"\newcommand{{\{_macro_name(tag, key)}}}"
                rf"{{{'--' if not np.isfinite(v) else f'{v:.0f}'}}}")
        # break-even as a multiple of the training set: an emulator repays its
        # own snapshots.
        n_tr = cat_meta.get("n_train")
        ratio_star = (amort.get("cross_rbm", np.nan) / float(n_tr)
                      if n_tr else np.nan)
        lines.append(rf"\newcommand{{\{_macro_name('RatioStar', key)}}}"
                     rf"{{{'--' if not np.isfinite(ratio_star) else f'{ratio_star:.2f}'}}}")
        # from the blocks: a macro is quoted next to a figure and must describe
        # the same run.
        lines.append(rf"\newcommand{{\{_macro_name('Ntrain', key)}}}"
                     rf"{{{cat_meta.get('n_train', '')}}}")
        lines.append(rf"\newcommand{{\{_macro_name('Nb', key)}}}"
                     rf"{{{man_meta.get('nb', '')}}}")

        # paired win fraction, as an integer percentage: the trials are
        # correlated within a draw.
        notes = views.error_distribution(key)["distribution"].notes
        for note, tag in (("win_rbm", "WinRbm"),):
            v = notes.get(note, np.nan)
            lines.append(rf"\newcommand{{\{_macro_name(tag, key)}}}"
                         rf"{{{'--' if not np.isfinite(v) else f'{100 * v:.0f}'}}}")
        for note, tag in (("n_energy_rbm", "NEnRbm"), ("n_energy", "NEn"),
                          ("n_trial", "NTrial")):
            lines.append(rf"\newcommand{{\{_macro_name(tag, key)}}}"
                         rf"{{{notes.get(note, '--')}}}")

        # mesh-scan endpoints, for the LROM asymptotic-claim sentence. A missing
        # scaling block costs only these two numbers.
        try:
            mesh = views.online_vs_mesh(key)["ratio"].notes
        except Exception:
            mesh = {}
        for note, tag in (("ratio_lo", "MeshLo"), ("ratio_hi", "MeshHi")):
            v = mesh.get(note, np.nan)
            lines.append(rf"\newcommand{{\{_macro_name(tag, key)}}}"
                         rf"{{{'--' if not np.isfinite(v) else f'{v:.2f}'}}}")

        # operating point of each method, same selection table_cost prints (both
        # call operating_rows).
        solver, configs = operating_rows(key)
        # what the affine split alone is worth before any reduction.
        lines.append(rf"\newcommand{{\{_macro_name('GainSplit', key)}}}"
                     rf"{{{solver['t_full'] / solver['t_V']:.1f}}}")
        for c in configs:
            t = c["tag"].title()          # Rbm, Lrom
            for tag, val in ((f"GainV{t}", f"{c['gain_V']:.1f}"),
                             (f"Ton{t}", f"{c['cost']:.2f}"),
                             (f"LMed{t}", _log(c["err"])),
                             (f"LPtail{t}", _log(c["p95"])),
                             (f"OkMed{t}", _verdict_error(c["err"])),
                             (f"OkTail{t}", _verdict_error(c["p95"])),
                             (f"OkGain{t}", _verdict_gain(c["gain_V"]))):
                lines.append(rf"\newcommand{{\{_macro_name(tag, key)}}}{{{val}}}")

    # campaign numbers: a crossing of two straight lines whose slopes are
    # measured, so it regenerates with them.
    from .api import campaign
    camp = campaign(1e5, systems=systems)
    for key in systems:
        rows = camp.loc[key]
        cross = rows["N_cross"].iloc[0] if "N_cross" in rows else np.nan
        # two significant figures: the crossing is where two timing lines meet
        # and the timings reproduce only to tens of per cent.
        lines.append(rf"\newcommand{{\{_macro_name('Ncross', key)}}}"
                     rf"{{{'--' if not np.isfinite(cross) else _sigfig(cross, 2)}}}")
        lines.append(rf"\newcommand{{\{_macro_name('Cheaper', key)}}}"
                     rf"{{{rows['cheaper_at_N'].iloc[0]}}}")
        for m in ("RBM", "LROM"):
            if m in rows.index:
                lines.append(rf"\newcommand{{\{_macro_name('Tcamp' + m.title(), key)}}}"
                             rf"{{{rows.loc[m, 'T_min']:.1f}}}")
        lines.append(rf"\newcommand{{\{_macro_name('TcampSolver', key)}}}"
                     rf"{{{rows['solver_T_min'].iloc[0]:.0f}}}")
    return "\n".join(lines) + "\n"


