BUILDERS = {"t_manifold": table_manifold, "t_cost": table_cost,
            "t_interior": table_interior, "t_budget": table_budget,
            "t_macros": macros}


def write_all(systems=SUITE, only=None):
    """Write every table; report what was written and what could not be.

    A builder that raises does not abort the rest -- its failure is returned as
    a row.
    """
    target = out_dir()
    target.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, build in BUILDERS.items():
        if only and name not in only:
            continue
        path = target / f"{name}.tex"
        try:
            text = build(systems)
        except Exception as exc:
            rows.append(dict(table=name, state=f"{type(exc).__name__}: {exc}"[:70],
                             path="", bytes=0))
            continue
        path.write_text(text, encoding="utf-8")
        rows.append(dict(table=name, state="written", path=str(path),
                         bytes=len(text.encode("utf-8"))))
    return pd.DataFrame(rows).set_index("table")
