#: Appended to table_budget's suite. alpha+d is the case the argument predicts
#: to be neutral (its coupling parameter also sits on the diagonal): the row
#: that does not move is what makes the others a measurement.
BUDGET_CONTROL = "alpha_d"

#: n+58Ni: a one-phonon vibrational coupling on a 0+ ground state has no
#: reorientation because <0|Y_lambda|0> vanishes, so the deformation is absent
#: from the diagonal whatever the model does -- unlike alpha+24Mg and n+238U,
#: where the reorientation is switched off by a modelling choice.
BUDGET_PHYSICAL = "n58Ni"


def table_budget(systems=SUITE):
    """Joint against split predictor budget, at fixed total K.

    Only coupled systems appear. The joint and split errors on each observable
    are divided, not both printed; a ratio below FLAT reads as no gain (timing
    and draw scatter at that size).
    """
    FLAT = 1.5
    rows, n_valid = [], None
    for extra in (BUDGET_PHYSICAL, BUDGET_CONTROL):
        if extra not in systems:
            systems = tuple(systems) + (extra,)
    for key in systems:
        system = SYSTEMS[key]
        try:
            d, meta = cache.read(key, "budget")
        except Exception:
            continue                            # skipped by the run, not missing
        n_valid = meta.get("n_valid", n_valid)
        med = lambda k: float(np.nanmedian(np.asarray(d[k], dtype=float)))  # noqa: E731

        def gain(joint, split):
            j, s = med(joint), med(split)
            return j / s if np.isfinite(j) and np.isfinite(s) and s > 0 else np.nan

        g_el, g_in = gain("err_el_joint", "err_el_split"), gain("err_in_joint", "err_in_split")
        travel = float(meta["diag_moves"])

        def cell(g):
            """The ratio joint/split. A ratio at or below 1/FLAT is a loss and
            is coloured as one; between the two bands is a dash."""
            if not np.isfinite(g):
                return "--"
            if g >= FLAT:
                return rf"$\times{g:.0f}$"
            if g <= 1.0 / FLAT:
                return rf"\textcolor{{Vloss}}{{$\divisionsymbol{1.0 / g:.1f}$}}"
            return "--"

        # how far the diagonal travels when the coupling parameter crosses its
        # box, relative to its own size; exactly zero is forbidden by a
        # selection rule.
        t = "$0$" if travel == 0.0 else rf"${travel:.1g}$".replace("e-0", r"\times10^{-") \
            .replace("$1\\times10^{", "$10^{")
        if "10^{" in t and not t.endswith("}$"):
            t = t[:-1] + "}$"

        applied = ("split" if meta.get("split_applied", True) else "joint")
        rows.append(
            rf"{system.label} & {meta.get('coup_label', '')} & "
            rf"${meta['K_diag']}{{+}}{meta['K_coup']}$ & "
            rf"{t} & {cell(g_el)} & {cell(g_in)} & \emph{{{applied}}} \\")

    caption = (
        rf"Joint against split predictor budget, at fixed total $K$: \emph{{split}} "
        rf"divides $K$ as shown, \emph{{joint}} spends it all on the diagonal, and "
        rf"everything else is held equal over ${n_valid}$ validation draws. "
        rf"Column~4 is how far the diagonal potential travels, relative to its own "
        rf"size, when the coupling parameter of column~2 crosses its box; it is the "
        rf"quantity the rule of Section~\ref{{subsec:budget}} is read on. "
        rf"Columns~5 and~6 are the median error of the joint budget divided by that "
        rf"of the split one, on the elastic and on the inelastic element: "
        rf"$\times n$ means the split is $n$ times better, $\divisionsymbol n$ that it is $n$ "
        rf"times worse, and a dash that the two lie within a factor of ${FLAT}$. "
        rf"The last column is the allocation the autocalibration applies, which "
        rf"follows the rule rather than a choice: split where the diagonal does not "
        rf"move, joint everywhere else. $n+{{}}^{{58}}$Ni is the only system whose "
        rf"coupling parameter is absent from the diagonal exactly, by the selection "
        rf"rule of Section~\ref{{subsec:cc}}.")

    return _tabular(
        [r"& & & & \multicolumn{2}{c}{gain from splitting} & \\",
         r"\cmidrule(lr){5-6}",
         r"System & param. & $K_{\rm diag}{+}K_{\rm coup}$ "
         r"& diagonal travel & elastic & inelastic & applied \\"],
        rows, "llrlrrl", caption, "tab:budget", "budget")


